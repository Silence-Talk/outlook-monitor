"""Jev-style typed decisions about each message, with probabilities.

Jev (TypeSafe AI) is a "System One" model: it does not write prose. You send a
`state` plus typed questions and it returns typed answers, a probability per
option, and a confidence. The same wire protocol, `POST /v1/systemone`, is
implemented locally by open-source System One models, so this module talks to
the protocol once and points at either backend:

  hosted Jev   base_url https://api.typesafe.ai   model jev-latest
               needs TYPESAFE_API_KEY; $42 per 1B input tokens, output free,
               64k tokens per request (32k for state + longest question).
               https://docs.typesafe.ai/introduction

  Von (local)  base_url http://127.0.0.1:8000     model von-latest
               github.com/wfzyx/von — 395M ModernBERT encoder, Apache-2.0,
               one forward pass, CPU-served (OpenVINO preferred over torch CPU;
               p50 0.34 s measured on CPU). `von serve` exposes /v1/systemone.

Question types (docs.typesafe.ai/primitives):
  choice — one option from a set      -> choice, probabilities, confidence
  score  — a level on an ordered scale -> score, probabilities, legend, confidence
  noul   — yes/no probability          -> probability, confidence

Confidence is what makes the pattern usable: act when it is high, escalate
when it is low. The 0.80 gate below mirrors Von's documented default.
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request

DEFAULT_BASE_URL = "https://api.typesafe.ai"
DEFAULT_MODEL = "jev-latest"
CONFIDENCE_GATE = 0.80
STATE_BODY_CHARS = 1200  # Jev's budget is 32k for state + longest question

# One request per message: every question is answered in the same pass, so
# adding a question costs nothing.
TRIAGE_QUESTIONS = {
    "kind": {
        "type": "choice",
        "instructions": "What kind of message is this, by sender and content?",
        "criteria": {
            "personal": "Written by a real person to a real person; a reply "
                        "or a request that expects a human answer",
            "notification": "Generated by a service to tell you something "
                            "happened: comments, mentions, shares, activity",
            "newsletter": "Editorial content or an unsubscribe link; written "
                          "for an audience, not about one specific event",
            "security": "A security or sign-in alert that may need action",
            "financial": "Bank, payment, receipt, or transaction record",
            "other": "None of the above fits",
        },
    },
    "urgency": {
        "type": "noul",
        "instructions": "Does this message ask something of you right now, "
                        "rather than merely informing you?",
    },
    "attention": {
        "type": "score",
        "instructions": "How much does this message deserve your attention "
                        "today?",
        "criteria": {
            "0": "Ignore it: noise, or information you already acted on",
            "1": "Worth reading later; no action expected now",
            "2": "Read it now; a decision or reply is expected of you",
        },
    },
}


def ask(state: str, questions: dict, *, base_url: str = DEFAULT_BASE_URL,
        model: str = DEFAULT_MODEL, api_key: str | None = None,
        timeout: float = 30.0) -> dict:
    """Send one System One request; return the answers map keyed by question id."""
    body = json.dumps(
        {"state": state, "model": model, "questions": questions},
        ensure_ascii=False,
    ).encode("utf-8")
    req = urllib.request.Request(
        f"{base_url.rstrip('/')}/v1/systemone", data=body,
        headers={"Content-Type": "application/json"},
    )
    key = api_key if api_key is not None else os.environ.get("TYPESAFE_API_KEY")
    if key:
        req.headers["Authorization"] = f"Bearer {key}"
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        payload = json.loads(resp.read().decode("utf-8"))
    # The envelope differs between implementations; answers live under
    # "answers" for Jev, and some local servers return the map bare.
    if isinstance(payload, dict):
        return payload.get("answers") or payload.get("questions") or payload
    return {}


def message_state(msg: dict) -> str:
    """Render a message as the `state` Jev evaluates."""
    parts = [
        f"Sender: {msg.get('sender_email') or msg.get('sender_name') or '?'}",
        f"Subject: {msg.get('subject') or ''}",
        f"Received: {msg.get('received_time') or ''}",
    ]
    body = (msg.get("body") or "").strip()
    if body:
        parts.append(f"Body: {body[:STATE_BODY_CHARS]}")
    return "\n".join(parts)


def gate(answers: dict, threshold: float = CONFIDENCE_GATE) -> dict:
    """Split answers into what software may act on and what needs review."""
    auto, review = {}, {}
    for qid, ans in answers.items():
        conf = ans.get("confidence")
        if conf is None:
            conf = ans.get("probability")
        (auto if (conf or 0) >= threshold else review)[qid] = ans
    return {"auto": auto, "review": review}


def build_questions(options: dict) -> dict:
    """Triage questions plus one `service` question built from the scripts.

    `options` is the namespaced {"source:label": description} map the scripts
    advertise, so the answer the model returns is a valid argument by
    construction.
    """
    questions = dict(TRIAGE_QUESTIONS)
    if options:
        questions["service"] = {
            "type": "choice",
            "instructions": "If you ran one external lookup now, which single "
                            "option would answer what this message asks? "
                            "Choose none when no lookup fits the words used.",
            "criteria": {**options, "none": "No lookup would answer this; "
                                           "the message is chitework or needs "
                                           "a human to read it"},
        }
    return questions


def pick(answers: dict) -> tuple[str | None, float]:
    """The `service` answer as (namespaced option, confidence)."""
    ans = answers.get("service") or {}
    return (ans.get("choice"), ans.get("confidence") or 0.0)


def decide(msg: dict, *, base_url: str = DEFAULT_BASE_URL,
           model: str = DEFAULT_MODEL, questions: dict | None = None) -> dict:
    """Classify one message; returns {} if the endpoint is unreachable."""
    try:
        answers = ask(message_state(msg),
                      questions or TRIAGE_QUESTIONS,
                      base_url=base_url, model=model)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        print(f"decision endpoint unreachable: {type(exc).__name__}: {exc}")
        return {}
    return {"answers": answers, **gate(answers)}
